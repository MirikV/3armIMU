/**
 * «Прицел» предплечья: азимут, возвышение и скрутка — три числа, которые честно
 * наблюдаются по ОДНОМУ кватерниону с часов.
 *
 * ── Фундаментальный предел (читать до того, как придумывать четвёртую команду) ──
 * С часов приходит только ориентация. Ориентация — это ровно три степени свободы:
 * куда смотрит ось предплечья (две) и насколько кисть повёрнута вокруг этой оси (одна).
 * Перенос руки в пространстве без смены ориентации даёт побитно одинаковый пакет —
 * «приблизить/отдалить» из этого потока не извлекается никаким алгоритмом. Поэтому
 * вылет манипулятора задаётся настройкой, а не рукой; см. стратегию 'direct'.
 *
 * ── Почему считаем в системе Android, а не в системе сцены ──
 * Переход в Babylon включает перестановку МИРОВЫХ осей Y↔Z (матрица P в frames.js).
 * После неё ось предплечья (0,1,0) численно совпадает с мировой вертикалью сцены, и
 * swing-twist разложение по «оси предплечья» начинает засчитывать поворот всей руки
 * вокруг вертикали как скрутку кисти — на 90° поворота корпуса приходилось до 90°
 * ложной скрутки. В правой тройке Android ось предплечья (+Y устройства) и мировая
 * вертикаль (+Z ENU) — разные оси, и путаницы нет.
 *
 * ── Почему сначала снимается курс, и только потом берётся скрутка ──
 * Одного swing-twist на android-кватернионе мало. Разложение q = swing ⊗ twist берёт
 * скрутку относительно НЕПОДВИЖНОЙ опорной позы, поэтому поворот всей руки вокруг
 * вертикали при поднятом предплечье всё равно частично протекает в twist (при
 * возвышении 45° поворот корпуса на 90° давал 45° «скрутки»). Лечится тем, что
 * ориентация раскладывается в привычную тройку «курс → возвышение → скрутка»:
 *   q = Yaw(азимут) ⊗ tilt,  скрутка = twist(tilt) вокруг оси предплечья.
 * Мировое рыскание целиком уходит в Yaw, tilt от него не зависит вообще (проверено
 * тестом на возвышениях от −89° до +60°: скрутка не меняется ни на 1e-10 градуса).
 *
 * ── Вырождение ──
 * Предплечье строго вертикально ⇒ азимут не определён (та же дыра, что у курса в
 * getOrientation()). Отдаём horizontal = |горизонтальная проекция оси| — вызывающий
 * по ней решает, доверять азимуту или удерживать предыдущий.
 */

import { quat, normalize, rotateVector } from './quat.js';
import { splitHeading, babylonQuatToAndroid } from './frames.js';
import { swingTwist } from './swingTwist.js';

/** Ось предплечья в осях устройства: «12 часов» циферблата смотрят к кисти. */
export const DEVICE_FOREARM_AXIS = Object.freeze({ x: 0, y: 1, z: 0 });

/**
 * @typedef {Object} ForearmAim
 * @property {number} azimuth    курс оси предплечья, рад: компасный (по часовой от
 *                               севера ENU), [-π, π]. У GAME_ROTATION_VECTOR он
 *                               относительный — начало снимается кнопкой обнуления.
 * @property {number} elevation  возвышение оси предплечья над горизонтом, рад,
 *                               [-π/2, π/2]. Это ровно −pitch из getOrientation().
 * @property {number} twist      скрутка кисти вокруг оси предплечья, рад, [-π, π],
 *                               правило правой руки относительно направления «к кисти».
 * @property {number} horizontal длина горизонтальной проекции оси, 0…1 — мера того,
 *                               насколько азимуту можно верить.
 * @property {boolean} degenerate скрутка не определена (поворот на 180° поперёк оси).
 */

/**
 * @param {{x,y,z,w}} qAndroid ориентация устройство→мир в ENU (после калибровки)
 * @returns {ForearmAim}
 */
export function forearmAim(qAndroid) {
  const q = normalize(qAndroid || quat());
  // Ось предплечья в мире: вторая колонка матрицы поворота.
  const dir = rotateVector(q, DEVICE_FOREARM_AXIS);
  const horizontal = Math.hypot(dir.x, dir.y);
  const azimuth = Math.atan2(dir.x, dir.y);
  const elevation = Math.asin(Math.max(-1, Math.min(1, dir.z)));

  const { tilt } = splitHeading(q);
  const { angle, degenerate } = swingTwist(tilt, DEVICE_FOREARM_AXIS);

  return { azimuth, elevation, twist: angle, horizontal, degenerate };
}

/** То же самое, когда на руках только кватернион сцены (перевод точный, см. frames.js). */
export function forearmAimFromBabylon(qBabylon) {
  return forearmAim(babylonQuatToAndroid(qBabylon || quat()));
}
