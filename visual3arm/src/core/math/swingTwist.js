/**
 * Swing-twist разложение кватерниона — развязка «куда смотрит ось» и «скрутка вокруг оси».
 *
 * ── Зачем ──
 * Углы Эйлера раскладывают поворот по ТРЁМ ФИКСИРОВАННЫМ (мировым) осям. Из-за этого
 * поворот вокруг собственной оси звена почти никогда не попадает целиком в один угол:
 * он «протекает» в соседние. На практике это выглядело так: пользователь крутит кисть
 * вокруг оси предплечья, eulerYXZ() отдаёт изменившийся pitch, а pitch уходил в плечо
 * и локоть робота — локоть ехал сам по себе. Swing-twist убирает причину: он раскладывает
 * поворот по ОДНОЙ выбранной оси, привязанной к звену, а не к миру.
 *
 * ── Постановка ──
 * Дан единичный кватернион q и единичная ось a. Ищем q = swing ⊗ twist, где
 *   twist — поворот ВОКРУГ a (его векторная часть коллинеарна a),
 *   swing — поворот БЕЗ скрутки вокруг a (его векторная часть ортогональна a).
 * Разложение в таком виде единственно (с точностью до двойного накрытия ±q).
 *
 * ── Вывод ──
 * Пусть q = (v, w). Проекция векторной части на ось: p = (v·a)·a, d = v·a.
 * Берём twist ∝ (p, w) и нормируем: m = hypot(d, w), twist = (a·d/m, w/m).
 * Тогда swing = q ⊗ twist⁻¹, и прямым перемножением:
 *   swing = ( [ w·(v − p) − d·(v × a) ] / m ,  m )
 * — её векторная часть ортогональна a (v − p ⊥ a по построению, v × a ⊥ a всегда),
 * значит у swing собственной скрутки вокруг a нет. Что и требовалось.
 *
 * ── Свойства, ради которых всё затевалось ──
 * 1. swing·a = q·a. Поворот вокруг a саму ось не двигает (twist·a = a), поэтому
 *    swing переводит a ровно туда же, куда и полный q. То есть НАПРАВЛЕНИЕ звена
 *    целиком описывается swing'ом.
 * 2. Домножение справа на скрутку — q' = q ⊗ Rot(a, φ) — это «покрутить кисть вокруг
 *    собственной оси предплечья». При этом swing' = swing (не меняется вообще),
 *    а угол twist'а растёт ровно на φ. Именно эта независимость и чинит баг.
 *
 * ── Вырождение ──
 * m → 0 означает w ≈ 0 и v ⊥ a, то есть поворот на 180° вокруг оси, перпендикулярной a.
 * Тогда скрутка физически не определена: любой twist даёт допустимое разложение
 * (аналог gimbal lock, но локализованный в одной точке, а не на целой плоскости).
 * Честно сообщаем об этом флагом degenerate и отдаём twist = identity, swing = q —
 * тождество q = swing ⊗ twist при этом остаётся точным, просто скрутку брать неоткуда.
 *
 * Знак угла: перед разложением приводим q к полусфере w ≥ 0. Кватернионы q и −q задают
 * один поворот, но угол скрутки у них отличается на 2π; фиксируя знак w, получаем
 * главное значение angle ∈ [−π, π].
 */

import { quat, normalize, multiply, invert } from './quat.js';

/** Ниже этого модуля проекции скрутка считается неопределённой. */
const TWIST_EPS = 1e-7;

function normalizeAxis(axis) {
  const n = Math.hypot(axis.x, axis.y, axis.z);
  if (n < 1e-12) return { x: 0, y: 1, z: 0 };
  return { x: axis.x / n, y: axis.y / n, z: axis.z / n };
}

/**
 * Разложить поворот на swing и twist относительно оси a.
 *
 * @param {{x,y,z,w}} q поворот
 * @param {{x,y,z}} axis ось разложения (в ЛОКАЛЬНЫХ осях того же тела, что и q)
 * @returns {{swing:{x,y,z,w}, twist:{x,y,z,w}, angle:number, degenerate:boolean}}
 *          angle — угол скрутки вокруг axis, радианы, [-π, π]
 */
export function swingTwist(q, axis = { x: 0, y: 1, z: 0 }) {
  const a = normalizeAxis(axis);
  let { x, y, z, w } = normalize(q || quat());
  if (w < 0) {
    x = -x;
    y = -y;
    z = -z;
    w = -w;
  }
  const qn = quat(x, y, z, w);

  const d = x * a.x + y * a.y + z * a.z;
  const m = Math.hypot(d, w);
  if (m < TWIST_EPS) {
    // 180° вокруг перпендикуляра к a: скрутка не определена, не выдумываем её.
    return { swing: qn, twist: quat(), angle: 0, degenerate: true };
  }

  const twist = quat((a.x * d) / m, (a.y * d) / m, (a.z * d) / m, w / m);
  const swing = normalize(multiply(qn, invert(twist)));
  // w >= 0 (мы это обеспечили), значит atan2 даёт [-π/2, π/2], а угол — [-π, π].
  const angle = 2 * Math.atan2(d, w);
  return { swing, twist, angle, degenerate: false };
}

/** Только угол скрутки вокруг оси, радианы. Ноль, если скрутка вырождена. */
export function twistAngleAbout(q, axis) {
  return swingTwist(q, axis).angle;
}

/** Только swing — поворот, отвечающий за направление оси. */
export function swingAbout(q, axis) {
  return swingTwist(q, axis).swing;
}
