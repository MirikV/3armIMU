/**
 * Отображение «прицела» руки в углы моторов робота — точка расширения.
 *
 * Стратегия — это чистая функция (aim, watchQuat, model, options) -> { имя: угол(рад) }.
 * Хочется другое правило — пишется новая стратегия и регистрируется в STRATEGIES,
 * остальной код не трогается.
 *
 * ── Что такое aim и почему он, а не поза руки ──
 * aim — результат forearmAim() (core/math/aim.js): азимут оси предплечья, её возвышение
 * и скрутка кисти вокруг этой оси. Это РОВНО ТО, что наблюдается с одного IMU на
 * запястье, — три числа, не больше и не меньше. Раньше сюда передавалась полная поза
 * руки (позиции плеча, локтя, запястья), но она была вычислена из тех же трёх чисел
 * плюс предположений о длинах костей: лишней информации в ней не было ни бита, зато
 * геометрия «запястье висит под плечом» загоняла цель в узкую колонну над основанием
 * и съедала ход моторов. Сейчас модель руки не нужна вовсе и удалена.
 *
 * ── Почему стратегия ровно одна ──
 * Осей у робота три, наблюдаемых величин три, и соответствие между ними взаимно
 * однозначное. Прежние стратегии ('reach' с обратной кинематикой, 'orientation',
 * 'chain') существовали, чтобы чем-то занять четвёртую ось и сравнить варианты; с
 * тремя осями сравнивать нечего. Реестр оставлен: под второй IMU (на плече) или под
 * другую механику добавляется запись, и ничего больше не меняется.
 *
 * ── Фундаментальный предел, о котором нельзя умалчивать ──
 * «Приблизить/отдалить» не наблюдается с одного IMU ни при каком алгоритме: перенос
 * руки вперёд без смены ориентации даёт побитно тот же пакет. У робота такой оси
 * теперь тоже нет — вылет задан геометрией стрелы и постоянен. Это не упрощение
 * ради простоты, а приведение управления в соответствие с тем, что реально измеряется.
 *
 * Единицы: радианы, метры. watchQuat — в системе Babylon (как и раньше).
 */

import { toRad } from '../math/quat.js';
import { forearmAim, forearmAimFromBabylon } from '../math/aim.js';

function clampNum(v, lo, hi) {
  return Math.min(hi, Math.max(lo, v));
}

/** Разность углов, приведённая к [-π, π] — чтобы не «ехать длинной дорогой». */
function wrapPi(a) {
  let x = a;
  while (x > Math.PI) x -= 2 * Math.PI;
  while (x < -Math.PI) x += 2 * Math.PI;
  return x;
}

/**
 * Азимут с удержанием у вырождения.
 *
 * Азимут — это atan2 от горизонтальной проекции оси, и он взрывается там, где проекция
 * коротка: при почти вертикальном предплечье дрожание в доли градуса даёт десятки
 * градусов поворота основания. Это и был симптом «кручу кисть — едет основание»:
 * скрутка в жизни никогда не бывает чистой, ось всегда уводит на пару градусов, а у
 * вертикали эти пара градусов умножались на десятку.
 *
 * Лечим плавным удержанием: пока проекция короче hold, азимут подтягивается к сырому
 * значению лишь частично, а в самом вырождении держится за предыдущий. Это не
 * «гистерезис» в смысле двух порогов — скачка при пересечении порога здесь нет вообще,
 * коэффициент непрерывен, а значит непрерывен и выход.
 *
 * @param {number} raw сырой азимут, рад
 * @param {number} projection длина горизонтальной проекции оси, 0…1
 * @param {number} hold порог, ниже которого начинается удержание
 * @param {number} prev предыдущий угол основания, рад
 */
export function heldAzimuth(raw, projection, hold, prev) {
  const k = hold > 0 ? clampNum(projection / hold, 0, 1) : 1;
  return prev + wrapPi(raw - prev) * k;
}

/** Предыдущий угол основания: нужен удержанию. Модель — часть сигнатуры, читать её можно. */
function prevBase(model, options) {
  const v = options.prevBase ?? model.angles?.base ?? 0;
  return Number.isFinite(v) ? v : 0;
}

/**
 * Наклон, при котором стрела лежит ГОРИЗОНТАЛЬНО ВПЕРЁД, градусы.
 *
 * Не подгоночная константа, а свойство модели: угол lift отсчитывается от локального
 * +Y звена, то есть от вертикали (lift = 0 — стрела строго вверх), и поворот на 90°
 * вокруг X кладёт её в горизонт. Проверено прямой кинематикой в tests/boomAim.test.js,
 * а не «подобрано, чтобы сошлось в одной точке».
 */
export const LIFT_HORIZON_DEG = 90;

/**
 * Настройки стратегии 'direct'. Градусы — это пользовательские ручки.
 *
 * ── Почему здесь больше нет растяжения диапазонов ──
 * Раньше «комфортный» ход предплечья (−80°…+45°) линейно растягивался на ход стрелы
 * (−20°…+100° от вертикали). Растяжение сдвигает нули: горизонтально вытянутая рука
 * (возвышение 0) давала наклон 23°, то есть стрелу, задранную на 67° над горизонтом, —
 * ровно жалоба «рука вперёд, а робот смотрит вверх». Хуже того, отображение было
 * физически НЕмонотонным сверху: возвышения +30° и +90° обе упирались в отрицательный
 * наклон, где стрела валится назад и её возвышение снова падает.
 *
 * Теперь отображение тождественное по построению: возвышение стрелы = возвышение
 * предплечья, то есть lift = 90° − возвышение. Ни одной свободной константы, верно
 * сразу на всём диапазоне, а не в одной точке.
 *
 * Оставшиеся ручки — это ОГРАНИЧЕНИЕ хода стрелы, а не растяжение: они могут только
 * подрезать края (например, если у вашей механики стрела не доходит до земли),
 * но не сдвигают и не масштабируют отображение внутри разрешённого окна.
 *
 * Ключи переименованы (было liftMinDeg/liftMaxDeg) намеренно: в localStorage у всех,
 * кто уже запускал прошлую версию, лежат старые значения −20 и 100, и под новым
 * смыслом они тихо зажали бы стрелу у горизонта — то есть баг вернулся бы ровно к тем,
 * кто на него жаловался. Смена имени заставляет loadSettings() взять новые дефолты
 * (см. pickKnown), и поднимать версию хранилища не приходится.
 */
export const DEFAULT_DIRECT = {
  /**
   * Рабочее окно наклона от вертикали: 0° — стрела строго вверх (рука поднята),
   * 90° — горизонтально вперёд, 180° — строго вниз (рука опущена вдоль тела).
   * Дефолт совпадает с механическими лимитами сустава: подрезать нечего.
   */
  liftTopDeg: 0,
  liftBottomDeg: 180,
  /** Возвышение, выше которого азимут удерживается (предплечье близко к вертикали). */
  azimuthHoldDeg: 75,
};

export const DEFAULT_GAIN = {
  base: 1,
  lift: 1,
  wristRoll: 1,
};

/**
 * Скрутка кисти → угол мотора wristRoll.
 *
 * Знак минус — не опечатка. Скрутка считается в ПРАВОЙ тройке Android, а мотор крутится
 * в ЛЕВОЙ тройке Babylon. Переход между ними сопрягает поворот матрицей с det = −1
 * (Q = diag(1,1,−1)), а такое сопряжение сохраняет ось и меняет знак угла:
 * Q·R(a,φ)·Q⁻¹ = R(a, −φ). Так что физическая скрутка +φ выглядит на экране правильно
 * именно как −φ вокруг той же оси.
 */
function twistToWristRoll(twist) {
  return -twist;
}

const STRATEGIES = {
  /**
   * Прямое покомпонентное отображение трёх наблюдаемых величин на три оси.
   *
   *   base      ← азимут предплечья, один к одному (обе системы отсчитывают азимут
   *               от «севера» к «востоку», так что переводить нечего);
   *   lift      ← возвышение предплечья один к одному: возвышение стрелы равно
   *               возвышению предплечья (см. LIFT_HORIZON_DEG);
   *   wristRoll ← скрутка кисти вокруг оси предплечья.
   *
   * Развязка осей здесь не «получается», а заложена: каждый мотор читает СВОЁ число
   * из forearmAim(), а азимут, возвышение и скрутка независимы по построению самого
   * разложения. Никакая скрутка не может тронуть основание, никакой поворот корпуса —
   * голову. Единственная связь, которая остаётся, — геометрическая и неустранимая:
   * у почти вертикального предплечья азимут вырождается (см. heldAzimuth).
   */
  direct(aim, watchQuat, model, options) {
    const g = options.gain;
    const cfg = { ...DEFAULT_DIRECT, ...options.direct };

    // Возвышение предплечья → возвышение стрелы, один в один.
    //
    // Наклон отсчитывается от вертикали, возвышение — от горизонта, навстречу друг
    // другу: lift = 90° − возвышение. Отсюда сразу три опорные позы без всякой
    // подгонки: рука вперёд (0°) → стрела вперёд (90°), рука вверх (+90°) → стрела
    // вверх (0°), рука вниз (−90°) → стрела вниз (180°).
    //
    // Коэффициент передачи умножает ОТКЛОНЕНИЕ от горизонта, а не сам угол: иначе
    // любой gain ≠ 1 снова уводил бы горизонтальную позу (а gain = −1, ради которого
    // ползунок и существует, давал бы вместо зеркального наклона полную бессмыслицу).
    const rawLift = toRad(LIFT_HORIZON_DEG) - aim.elevation * g.lift;

    // Обрезка по рабочему окну — настроечному и механическому сразу. На краю честнее
    // упереться, чем растянуть: внутри окна отображение остаётся точным до градуса,
    // а у упора стрела просто встаёт, и это видно глазом.
    const [limLo, limHi] = model?.limitsRad?.('lift') ?? [-Infinity, Infinity];
    const lift = clampNum(
      rawLift,
      Math.max(Math.min(toRad(cfg.liftTopDeg), toRad(cfg.liftBottomDeg)), limLo),
      Math.min(Math.max(toRad(cfg.liftTopDeg), toRad(cfg.liftBottomDeg)), limHi),
    );

    // Азимут у вертикали не определён; мерой доверия служит cos(возвышения) —
    // это ровно длина горизонтальной проекции единичной оси предплечья.
    const base = heldAzimuth(
      aim.azimuth,
      Math.cos(aim.elevation),
      Math.cos(toRad(cfg.azimuthHoldDeg)),
      prevBase(model, options),
    );

    if (options.diag) {
      options.diag.strategy = 'direct';
      options.diag.lift = lift;
      options.diag.twist = aim.twist;
      options.diag.twistDegenerate = aim.degenerate;
      options.diag.azimuthHeld = Math.cos(aim.elevation) < Math.cos(toRad(cfg.azimuthHoldDeg));
    }

    return {
      base: base * g.base,
      // gain уже учтён выше — он масштабирует отклонение от горизонта, а не угол.
      lift,
      wristRoll: twistToWristRoll(aim.twist) * g.wristRoll,
    };
  },
};

export const ROBOT_STRATEGIES = Object.keys(STRATEGIES);

export const DEFAULT_STRATEGY = 'direct';

/**
 * @param {string} strategy
 * @param {{x,y,z,w}} watchQuat ориентация часов в системе Babylon (после калибровки)
 * @param {import('./RobotModel.js').RobotModel} model
 * @param {{gain?: Record<string, number>, watchQuatAndroid?: {x,y,z,w},
 *          direct?: Object, prevBase?: number, diag?: Object}} [options]
 *        watchQuatAndroid — тот же поворот ДО перевода в сцену. Азимут, возвышение и
 *        скрутку считать можно только там (см. core/math/aim.js); если его не передали,
 *        он восстанавливается из watchQuat обратным преобразованием — точно, но лишней
 *        парой матричных умножений на пакет.
 *        diag — необязательный out-параметр: стратегия складывает туда диагностику.
 *        Сделано именно так, чтобы не менять возвращаемый тип стратегии — он остаётся
 *        чистой картой «сустав → радианы».
 * @returns {Record<string, number>} углы в радианах (ещё не обрезанные по лимитам)
 */
export function mapArmToRobot(strategy, watchQuat, model, options = {}) {
  const fn = STRATEGIES[strategy] || STRATEGIES[DEFAULT_STRATEGY];
  // Прицел считаем один раз на пакет и отдаём и стратегии, и панели.
  const aim = options.watchQuatAndroid
    ? forearmAim(options.watchQuatAndroid)
    : forearmAimFromBabylon(watchQuat);
  if (options.diag) options.diag.aim = aim;
  return fn(aim, watchQuat, model, { ...options, aim, gain: { ...DEFAULT_GAIN, ...options.gain } });
}
